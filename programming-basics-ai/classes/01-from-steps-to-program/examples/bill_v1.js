let price = 50;                                // ① ราคาต่อชิ้น
let qty = 3;                                   // ② จำนวนชิ้น
let total = price * qty;                       // ③ คูณกัน
console.log(`ยอดรวม ${total.toFixed(2)} บาท`);  // ④ แสดงยอดรวม
